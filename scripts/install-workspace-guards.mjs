#!/usr/bin/env node

/**
 * Install the workspace guard surfaces across every repository in the workspace root.
 *
 * Hooks are pointed at this repository's `.githooks` directory through each
 * repository's own `core.hooksPath`, so there is one hook source of truth and no
 * copied hook drift. The wrapper is exposed through a `bin/git` shim so external
 * tooling picks it up from PATH without knowing this repository exists.
 *
 * The installer only writes hook configuration and the shim. It never touches
 * tracked files, refs, or working-tree state in any repository.
 */

import { spawnSync } from "node:child_process";
import { chmodSync, existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptPath = fileURLToPath(import.meta.url);
const guardHome = path.resolve(path.dirname(scriptPath), "..");

export const HOOK_SURFACES = Object.freeze(["pre-commit", "pre-push", "reference-transaction"]);

export function resolveWorkspaceRoot({ env = process.env } = {}) {
  const configured = String(env.AGENTIC_WORKSPACE_ROOT || "").trim();
  return configured ? path.resolve(configured) : path.resolve(guardHome, "..");
}

export function discoverRepositories({ workspaceRoot, listEntries = (dir) => readdirSync(dir, { withFileTypes: true }) }) {
  return listEntries(workspaceRoot)
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith("."))
    .map((entry) => path.join(workspaceRoot, entry.name))
    .filter((candidate) => existsSync(path.join(candidate, ".git")))
    .sort();
}

export function buildShim({ home = guardHome } = {}) {
  return [
    "#!/bin/sh",
    "# Generated by agentic-canvas-os install-workspace-guards.",
    "# Place this directory ahead of git on PATH so external tooling is guarded.",
    "set -eu",
    `export AGENTIC_WORKSPACE_GUARD_HOME="${home}"`,
    `exec "${path.join(home, ".githooks", "git-guarded")}" "$@"`,
    "",
  ].join("\n");
}

export function installShim({ home = guardHome, write = writeFileSync, makeExecutable = chmodSync, ensureDir = mkdirSync } = {}) {
  const binDir = path.join(home, ".githooks", "bin");
  ensureDir(binDir, { recursive: true });
  const shimPath = path.join(binDir, "git");
  write(shimPath, buildShim({ home }), "utf8");
  makeExecutable(shimPath, 0o755);
  return { binDir, shimPath };
}

export function planHookInstall({ repositories, home = guardHome }) {
  const hooksPath = path.join(home, ".githooks");
  return repositories.map((repository) => Object.freeze({
    repository,
    hooksPath,
    isGuardHome: path.resolve(repository) === path.resolve(home),
  }));
}

export function applyHookInstall({ plan, spawn = spawnSync, write = (t) => process.stdout.write(t) }) {
  const applied = [];
  for (const entry of plan) {
    const result = spawn("git", ["config", "core.hooksPath", entry.hooksPath], {
      cwd: entry.repository,
      encoding: "utf8",
    });
    if (result.error) throw result.error;
    const ok = (result.status ?? 1) === 0;
    write(`[install-workspace-guards] ${ok ? "hooked" : "skipped"} ${path.basename(entry.repository)}\n`);
    if (ok) applied.push(entry.repository);
  }
  return applied;
}

export function runInstall({ env = process.env, spawn = spawnSync, write = (t) => process.stdout.write(t), argv = process.argv.slice(2) } = {}) {
  const workspaceRoot = resolveWorkspaceRoot({ env });
  const repositories = discoverRepositories({ workspaceRoot });
  const plan = planHookInstall({ repositories });
  const dryRun = argv.includes("--dry-run");

  write(`[install-workspace-guards] root ${workspaceRoot}\n`);
  write(`[install-workspace-guards] repositories ${repositories.length}\n`);

  if (dryRun) {
    for (const entry of plan) write(`[install-workspace-guards] would hook ${path.basename(entry.repository)} -> ${entry.hooksPath}\n`);
    write(`[install-workspace-guards] would install shim ${path.join(guardHome, ".githooks", "bin", "git")}\n`);
    return { workspaceRoot, repositories, applied: [], shim: null, dryRun: true };
  }

  const applied = applyHookInstall({ plan, spawn, write });
  const shim = installShim({});
  write(`[install-workspace-guards] shim ${shim.shimPath}\n`);
  write(`[install-workspace-guards] add to PATH: export PATH="${shim.binDir}:$PATH"\n`);
  write(`[install-workspace-guards] ok ${applied.length}/${repositories.length}\n`);
  return { workspaceRoot, repositories, applied, shim, dryRun: false };
}

if (process.argv[1] && path.resolve(process.argv[1]) === scriptPath) {
  try {
    runInstall();
  } catch (error) {
    process.stderr.write(`[install-workspace-guards] ${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  }
}
